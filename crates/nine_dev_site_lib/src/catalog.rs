//! Lookup of site-owned assets. The site declares the entries and embeds the bytes.

/// One build-time mapping. `url` is the exact encoded request path, including
/// its leading slash. Stable URLs carry the same content hash as immutable ones.
pub struct Entry {
    pub source: &'static str,
    pub url: &'static str,
    pub hash: &'static str,
}

pub struct Catalog(pub &'static [Entry]);

impl Catalog {
    pub fn by_source(&self, source: &str) -> Option<&'static Entry> {
        self.0.iter().find(|entry| entry.source == source)
    }

    /// Pass `uri.path()` without percent-decoding it.
    pub fn by_url(&self, path: &str) -> Option<&'static Entry> {
        self.0.iter().find(|entry| entry.url == path)
    }
}

/// Cache policy for an exact, stable URL.
pub enum AliasCache {
    Revalidate,
    Fixed(&'static str),
}

pub struct Alias {
    pub entry: Entry,
    pub cache: AliasCache,
}

/// A site's selected files and public aliases, generated by the build crate.
pub struct SiteCatalog {
    pub immutable: Catalog,
    pub aliases: &'static [Alias],
}

impl SiteCatalog {
    /// Prefer the immutable URL when a source also has a stable alias.
    pub fn by_source(&self, source: &str) -> Option<&'static Entry> {
        self.immutable.by_source(source).or_else(|| {
            self.aliases
                .iter()
                .map(|alias| &alias.entry)
                .find(|entry| entry.source == source)
        })
    }

    pub fn alias_by_url(&self, path: &str) -> Option<&'static Alias> {
        self.aliases.iter().find(|alias| alias.entry.url == path)
    }
}
